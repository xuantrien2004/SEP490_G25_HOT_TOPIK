package com.hottopik.service.exam;

import com.hottopik.entity.exam.*;
import com.hottopik.repository.exam.*;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@ActiveProfiles("test")
@Transactional
class LegacyProgramMigrationTest {
    @Autowired ProgramVersionSeeder seeder;
    @Autowired ProgramVersionRepository programs;
    @Autowired ProgramVersionItemRepository items;
    @Autowired StudyPlanRepository plans;
    @Autowired JdbcTemplate jdbc;
    @Autowired ProgramRoadmapService roadmap;

    private ProgramVersion legacyVersion() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.program_version_types (program_version_id BIGINT, question_type_id BIGINT, order_no INT)");
        jdbc.execute("ALTER TABLE dbo.question_types ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY");
        ProgramVersion p = new ProgramVersion();
        p.setVersionCode("legacy-" + UUID.randomUUID().toString().substring(0, 8));
        p.setStatus(ProgramStatus.ARCHIVED);
        p.setReviewOffsets("[2,7,14]");
        p.setPhaseSplit("[40,40,20]");
        p.setSessionsPerType(4);
        return programs.saveAndFlush(p);
    }

    private void legacyItem(ProgramVersion p, String code, int order) {
        Long id = jdbc.queryForObject("SELECT id FROM dbo.question_types WHERE code = ?", Long.class, code);
        jdbc.update("INSERT INTO dbo.program_version_types VALUES (?, ?, ?)", p.getId(), id, order);
    }

    @Test
    void restoresPublishedOrderAndRemapsCompletedMiniWithoutCompletingNewLessons() {
        ProgramVersion p = legacyVersion();
        legacyItem(p, "I-D1", 1);
        legacyItem(p, "I-N1", 2);
        legacyItem(p, "II-N1", 3);
        legacyItem(p, "II-V1", 4);
        StudyPlan plan = new StudyPlan();
        plan.setOwnerEmail(UUID.randomUUID() + "@example.com");
        plan.setProgramId(p.getId());
        plan.setVersionCode(p.getVersionCode());
        plan.setTrack(Track.TOPIK_I);
        plan.setStartDate(LocalDate.now().minusDays(3));
        plan.setTotalDays(60);
        plan.setItemsPerDay(2);
        plan.setMinutesPerDay(20);
        plan.setDoneKeys("1:0"); // In the faulty empty schedule this was MINI #1.
        plans.saveAndFlush(plan);

        seeder.run(null);
        items.flush();
        var restored = items.findWithTemplate(p.getId());
        assertEquals(List.of(QuestionTemplateCatalog.templateCode("I-D1"),
                QuestionTemplateCatalog.templateCode("I-N1"), QuestionTemplateCatalog.templateCode("II-N1")),
                restored.stream().map(i -> i.getTemplate().getCode()).toList());
        var preview = roadmap.preview(p, Track.TOPIK_I, 60, 2);
        assertEquals("NEW", preview.days().get(0).slots().get(0).kind());
        assertEquals(2, preview.newCount());
        assertEquals(6, preview.reviewCount());
        String done = plan.getDoneKeys();
        assertNotNull(done);
        assertFalse(List.of(done.split(",")).contains("1:0"));
        String[] position = done.split(":");
        var completed = preview.days().get(Integer.parseInt(position[0]) - 1).slots().get(Integer.parseInt(position[1]));
        assertEquals("MINI", completed.kind());
        assertEquals(1, completed.repetition());
        LocalDate start = plan.getStartDate();
        seeder.run(null);
        assertEquals(3, items.findWithTemplate(p.getId()).size());
        assertEquals(done, plan.getDoneKeys());
        assertEquals(start, plan.getStartDate());
    }

    @Test
    void emptyConfigurationDoesNotBecomeAnAllMiniSchedule() {
        ProgramVersion p = legacyVersion();
        assertThrows(ExamDomainException.class, () -> roadmap.preview(p, Track.TOPIK_I, 60, 2));
    }
}
