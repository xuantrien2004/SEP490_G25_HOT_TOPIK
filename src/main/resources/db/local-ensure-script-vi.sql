-- Profile local dùng H2. ddl-auto=update không thêm cột vào bảng đã có,
-- và có thể bỏ qua bảng mới. File này bù phần đó mỗi lần mở app.
ALTER TABLE IF EXISTS dbo.question_groups ADD COLUMN IF NOT EXISTS script_vi VARCHAR(4000);

CREATE TABLE IF NOT EXISTS dbo.placement_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_code VARCHAR(20) NOT NULL,
    type_code VARCHAR(10) NOT NULL,
    question_count INT NOT NULL,
    sort_order INT NOT NULL
);

CREATE TABLE IF NOT EXISTS dbo.placement_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    user_email VARCHAR(200),
    paper_code VARCHAR(20) NOT NULL,
    question_ids VARCHAR(2000) NOT NULL,
    total INT NOT NULL,
    answers_json VARCHAR(4000) NOT NULL,
    correct_count INT NOT NULL DEFAULT 0,
    listen_correct INT NOT NULL DEFAULT 0,
    listen_total INT NOT NULL DEFAULT 0,
    read_correct INT NOT NULL DEFAULT 0,
    read_total INT NOT NULL DEFAULT 0,
    points INT NOT NULL DEFAULT 0,
    completed_at TIMESTAMP,
    started_at TIMESTAMP NOT NULL
);

ALTER TABLE IF EXISTS dbo.placement_lines ADD COLUMN IF NOT EXISTS paper_code VARCHAR(20);
ALTER TABLE IF EXISTS dbo.placement_lines ADD COLUMN IF NOT EXISTS type_code VARCHAR(10);
ALTER TABLE IF EXISTS dbo.placement_lines ADD COLUMN IF NOT EXISTS question_count INT DEFAULT 0;
ALTER TABLE IF EXISTS dbo.placement_lines ADD COLUMN IF NOT EXISTS sort_order INT DEFAULT 0;

ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS user_id BIGINT;
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS user_email VARCHAR(200);
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS paper_code VARCHAR(20);
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS question_ids VARCHAR(2000);
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS total INT DEFAULT 0;
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS answers_json VARCHAR(4000) DEFAULT '{}';
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS correct_count INT DEFAULT 0;
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS listen_correct INT DEFAULT 0;
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS listen_total INT DEFAULT 0;
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS read_correct INT DEFAULT 0;
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS read_total INT DEFAULT 0;
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS points INT DEFAULT 0;
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS completed_at TIMESTAMP;
ALTER TABLE IF EXISTS dbo.placement_attempts ADD COLUMN IF NOT EXISTS started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;
